_overrides: dict[str, str] = {}
_fetched_at: float = 0.0


def get(key: str, **vars) -> str:
    """Эффективный текст промпта: переопределение из админки или дефолт, с подстановкой $плейсхолдеров."""
    tpl = _overrides.get(key) or DEFAULTS[key]
    return Template(tpl).safe_substitute(**vars) if vars else tpl


def source(key: str) -> str:
    return "override" if key in _overrides else "default"


def overrides_count() -> int:
    return len(_overrides)


async def ensure_fresh() -> None:
    """Подтягивает переопределения с PROMPTS_URL не чаще, чем раз в PROMPTS_TTL_SECONDS.

    Любая ошибка (сеть, не-JSON, кривые ключи) не фатальна: остаются текущие/дефолтные промпты.
    """
    global _fetched_at
    if not settings.prompts_url:
        return
    now = time.time()
    if now - _fetched_at < settings.prompts_ttl_seconds:
        return
    _fetched_at = now  # ставим до запроса, чтобы ошибки не долбили URL на каждый вызов
    try:
        async with httpx.AsyncClient(timeout=5) as client:
            r = await client.get(settings.prompts_url)
            r.raise_for_status()
            data = r.json()
        raw = data.get("prompts", data) if isinstance(data, dict) else {}
        new = {
            k: v for k, v in raw.items()
            if k in DEFAULTS and isinstance(v, str) and v.strip()
        }
        skipped = [k for k in raw if k not in DEFAULTS]
        _overrides.clear()
        _overrides.update(new)
        log.info("[prompts] загружено переопределений: %d%s", len(new),
                 f", пропущено неизвестных ключей: {skipped}" if skipped else "")
    except Exception as e:  # noqa: BLE001
        log.warning("[prompts] не удалось получить %s: %s — используем текущие/дефолтные",
                    settings.prompts_url, e)
